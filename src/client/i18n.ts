const dictionaries = { fr, en };
export type TranslationKey = keyof typeof fr;
export type TFunction = (key: TranslationKey, values?: Record<string, string | number>) => string;

export function translate(locale: Locale, key: TranslationKey, values?: Record<string, string | number>): string {
  let output: string = dictionaries[locale][key];
  for (const [name, value] of Object.entries(values ?? {})) {
    output = output.replaceAll(`{{${name}}}`, String(value));
  }
  return output;
}

export function errorTranslationKey(code: string): TranslationKey {
  const key = `error${code}` as TranslationKey;
  return key in fr ? key : 'errorGeneric';
}
